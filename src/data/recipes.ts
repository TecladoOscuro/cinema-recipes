import type { Recipe } from '../types'

export function getDifficultyColor(difficulty: Recipe['difficulty']): string {
  switch (difficulty) {
    case 'Muy fácil': return 'bg-emerald-600/20 text-emerald-400'
    case 'Fácil': return 'bg-green-700/30 text-green-400'
    case 'Media': return 'bg-amber-600/30 text-amber-400'
    case 'Media-Alta': return 'bg-orange-700/30 text-orange-400'
    case 'Difícil': return 'bg-red-700/30 text-red-400'
    case 'Avanzado': return 'bg-purple-700/30 text-purple-400'
  }
}

export function getRecipeById(id: string): Recipe | undefined {
  return recipes.find((r) => r.id === id)
}

